/* Глава 9, шаг 1 (shag1.c): опрос "в лоб" - каждый опрос при нажатой кнопке даёт +1. */
#include "sim.h"
#include "09-knopka/shag1.c"
#define BTN PIN('C', 1)
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  sim_start();
  CHECK(pin_pullup(BTN), "PC1: вход с подтяжкой");
  T0(200); CHECK(num()==0, "кнопку не трогаем: 0000");
  btn_down(BTN); T0(7);
  CHECK(t1==7, "кнопка нажата 7 опросов подряд: +7 (в лоб считается каждый опрос по 2 мс)");
  btn_up(BTN); T0(100);
  CHECK(t1==7 && num()==7, "отпустили: счёт стоит");
  btn_tap(BTN);
  CHECK(t1!=8, "одно нажатие с дребезгом даёт намного больше +1");
  return sim_done("09/shag1");
}
