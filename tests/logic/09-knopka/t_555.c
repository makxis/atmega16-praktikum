/* Глава 9, задание 1 (555.c, программа преподавателя): нет подтяжки на PC1.
   В модели висящий вход читается как 0, поэтому 555.c считает сам, без нажатий. */
#include "sim.h"
#include "09-knopka/555.c"
#define BTN PIN('C', 1)
static const unsigned char KOD[10] = {0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  for(int d = 0; d < 10; d++) Kod7[d] = (char)KOD[d];
  sim_start();
  CHECK(!pin_pullup(BTN), "в 555.c подтяжки на PC1 нет");
  CHECK(pin_level(BTN)==0, "кнопка отпущена, а вход висит (в модели читается 0)");
  T0(1000);
  CHECK(num() > 0, "555.c считает сам: кнопку никто не нажимал, а на индикаторе не 0000");
  return sim_done("09/555");
}
