/* Глава 9, шаг 2 (shag2.c): пауза 0,6 с после нажатия, счёт до 9999 с переносами. */
#include "sim.h"
#include "09-knopka/shag2.c"
#define BTN PIN('C', 1)
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  sim_start();
  T0(200); CHECK(num()==0, "старт 0000, сам не считает");
  btn_press(BTN); CHECK(t1==1 && t2==0, "нажатие с дребезгом = 0001");
  T0(301); CHECK(t1==2, "держим ещё 0,6 с: автоповтор, 0002");
  btn_release(BTN); T0(400); CHECK(num()==2, "отпустили: 0002");
  t1 = 9; t2 = 8; t3 = 0; t4 = 0; inc(); CHECK(num()==90, "0089 + 1 = 0090");
  t1 = 9; t2 = 9; t3 = 9; t4 = 9; inc(); CHECK(num()==0, "9999 + 1 = 0000");
  btn_down(BTN); run_ms(3000); btn_up(BTN);
  CHECK(t1==5, "удержание 3 с модельного времени: +1 раз в ~0,6 с, всего 5");
  return sim_done("09/shag2");
}
