/* Глава 10, вариант А: kbd_hex.c. Клавиатура = провода строка-столбец (kbd_pins), нажатие с дребезгом.
   Проверяем: до первого прерывания все столбцы в 1; без нажатий прочерк (нет фантомов, подтяжки строк
   на месте); каждая из 16 клавиш даёт свой код 0..9, A..F (* = E, # = F); удержание не мешает. */
#include "sim.h"
#include "10-klaviatura/kbd_hex.c"
static const int R[4] = {PIN('B', 2), PIN('B', 3), PIN('C', 0), PIN('C', 1)};   /* СТР1..СТР4 */
static const int C[4] = {PIN('B', 5), PIN('B', 6), PIN('B', 7), PIN('D', 7)};   /* СТЛ1..СТЛ4 */
static const int code[4][4] = {{1, 2, 3, 10}, {4, 5, 6, 11}, {7, 8, 9, 12}, {14, 0, 15, 13}};
int main(void){
  kbd_pins(R, C);
  disp_digits(PIN('B', 4), -1, -1, -1);                 /* один разряд на PB4, всегда включён */
  sim_start();
  CHECK(pin_out(C[0]) == 1 && pin_out(C[1]) == 1 && pin_out(C[2]) == 1 && pin_out(C[3]) == 1,
        "после main() до первого прерывания все столбцы в 1 (PORTD задан, PD7 = 1)");
  CHECK(pin_out(PIN('B', 4)) == 0, "разряд PB4 включён (0)");
  T0(100);
  CHECK(disp_digit(0) == -2, "без нажатий горит прочерк: фантомных клавиш нет");
  CHECK(pin_pullup(R[0]) && pin_pullup(R[1]) && pin_pullup(R[2]) && pin_pullup(R[3]),
        "подтяжка на всех четырёх строках (PB2, PB3 не затёрты записью PORTB)");
  int bad = 0;
  for(int r = 0; r < 4; r++)
    for(int c = 0; c < 4; c++){
      kbd_tap(r, c, 50);                                /* ~100 мс: обычное нажатие */
      int d = disp_digit(0);
      if(d != code[r][c]){ printf("  клавиша [%d][%d]: на индикаторе %d, ожидалось %d\n", r, c, d, code[r][c]); bad++; }
    }
  CHECK(bad == 0, "все 16 клавиш дают свой код (0..9, A..F; * = E, # = F)");
  kbd_tap(1, 1, 1000);                                  /* "5", держим 2 с */
  CHECK(disp_digit(0) == 5, "удержание 2 с: на индикаторе 5");
  int ok = 1;                                           /* за проход столбцы по очереди в 0, остальные в 1 */
  for(int k = 0; k < 8; k++){
    T0(1);
    int zeros = 0;
    for(int c = 0; c < 4; c++) if(pin_out(C[c]) == 0) zeros++;
    if(zeros != 1) ok = 0;
  }
  CHECK(ok, "в каждый момент в 0 ровно один столбец");
  pin_wire(R[0], C[1]); pin_wire(R[2], C[1]);           /* "2" и "8" сразу: один столбец, две строки */
  T0(60);
  CHECK(disp_digit(0) == 2, "две клавиши одного столбца: программа берёт верхнюю (2, а не 8)");
  pin_unwire(R[0], C[1]); pin_unwire(R[2], C[1]); T0(60);
  pin_ext(PIN('C', 0), 0); T0(60);                      /* забытый провод кнопки на PC0 (СТР3) */
  CHECK(disp_digit(0) == 12, "кнопка на PC0 срабатывает как клавиша C");
  pin_ext(PIN('C', 0), -1); T0(60);
  pin_ext(PIN('C', 1), 0); T0(60);                      /* кнопка на PC1 (СТР4) */
  CHECK(disp_digit(0) == 13, "кнопка на PC1 срабатывает как клавиша D");
  pin_ext(PIN('C', 1), -1); T0(60);
  return sim_done("10/kbd_hex");
}
