/* Мутант shag2.c с переносом десятков секунд на 10 (tests/mutants/08-shag2-carry.json):
   тест ловит его, если 61 с показаны не как 01:01. */
#include "sim.h"
#include "08-chasy/shag2__carry.c"
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  sim_start();
  T1(61);
  CHECK(num()==61, "мутант пойман: 61 с показаны как 00:61 вместо 01:01");
  return sim_done("08/shag2 мутант перенос на 10");
}
