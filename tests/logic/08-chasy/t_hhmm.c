/* Глава 8, доработка 2 (hhmm.c): часы ЧЧ:ММ 00:00..23:59. */
#include "sim.h"
#include "08-chasy/hhmm.c"
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  sim_start();
  CHECK(OCR1A==31249 && num()==0, "старт: 00:00, OCR1A=31249");
  /* быстрая проверка из комментария в main(): старт 23:58, OCR1A=311, через ~1,2 с 00:00 */
  t4 = 2; t3 = 3; t2 = 5; t1 = 8; OCR1A = 311;
  run_ms(1300); CHECK(num()==0, "быстрая проверка: 23:58 + 1,3 с при OCR1A=311 -> 00:00");
  OCR1A = 31249; TCNT1 = 0; t1 = t2 = t3 = t4 = 0; sec = 0; show();
  T1(59); CHECK(num()==0, "59 с: ещё 00:00");
  T1(1); CHECK(num()==1, "60 с: 00:01");
  T1(9*60*60 + 59*60 - 60); CHECK(num()==959, "09:59");
  T1(60); CHECK(num()==1000, "10:00: перенос из единиц часов в десятки");
  T1(13*60*60 + 59*60); CHECK(num()==2359, "23:59");
  T1(60); CHECK(num()==0, "полночь: 00:00");
  return sim_done("08/hhmm");
}
