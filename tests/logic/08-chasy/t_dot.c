/* Глава 8, доработка 1 (dot.c): точка после единиц минут мигает, Timer1 2 раза в секунду. */
#include "sim.h"
#include "08-chasy/dot.c"
/* Перед чтением индикатора - полный круг развёртки (4 вызова Timer0): после ручного T1() или правки
   переменных разряд, который горит в этот момент, иначе показал бы старый код. */
static int num(void){ T0(4); return disp_num(); }
int main(void){
  sim_start();
  CHECK(OCR1A==15624, "OCR1A=15624: Timer1 2 раза в секунду");
  CHECK(num()==0 && !(disp_code(1) & 0x80), "старт: 00:00, точка не горит");
  T1(1); CHECK(num()==0 && (disp_code(1) & 0x80), "0,5 с: 00:00, точка горит");
  T1(1); CHECK(num()==1 && !(disp_code(1) & 0x80), "1,0 с: 00:01, точка погасла");
  T1(1); T0(4); CHECK(!(disp_code(0) & 0x80) && !(disp_code(2) & 0x80) && !(disp_code(3) & 0x80),
               "в других разрядах точки нет");
  T1(2*3600-3); CHECK(num()==0, "через час: 00:00");
  isr_calls_reset(); run_ms(10200);
  CHECK(isr_calls("TIMER1_COMPA")==20, "10,2 с модельного времени: 20 прерываний Timer1");
  CHECK(num()==10, "по модельному времени: 00:10");
  return sim_done("08/dot");
}
