// Глава 11: частотомер. Считаем фронты сигнала на PB2 (внешнее прерывание INT2) ровно 1 секунду
// и показываем, сколько насчитали: это и есть частота в герцах (0..9999 Гц, больше - "----").
// Для самопроверки программа сама выдаёт на PB3 меандр 488 Гц (Timer0 в режиме Fast PWM):
// перемычка PB3 - PB2, и на индикаторе 0488 или 0489.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка       -> PD0..PD7  (1 = горит)
//   разряды 1..4               -> PB4..PB7  (0 = разряд включён)
//   измеряемый сигнал          -> PB2       (вход INT2 с подтяжкой, считаем фронты из 0 в 1)
//   перемычка для самопроверки -> PB3       (выход OC0, меандр 488 Гц; второй конец перемычки - в PB2)
//   гнёзд занято: 14 из 16
// Если сигнал идёт с другого модуля (генератор, второй "Контроллер ПУ"), соедините их общий провод.
// Сигнал только с уровнями 0 и 5 В.
//
// Ограничение: пока идёт обработчик Timer1 (деления в show_num, около 0,14 мс), INT2 ждёт,
// а флаг INTF2 помнит только один фронт. Выше примерно 7 кГц возможна потеря 1 фронта за секунду.

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

unsigned char i1=0;                     // номер разряда, который горит сейчас (0..3)
char Mas[4]={0xE4,0xD4,0xB4,0x74};      // маски разрядов {PB4..PB7} + подтяжка PB2 (бит 0x04)
char Ind[4];                            // что горит в каждом разряде (коды сегментов)
char kod7[10]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};  // коды цифр 0..9
volatile unsigned int cnt=0;            // фронты за текущую секунду (меняется в прерывании)

void show_num(unsigned int n)           // показать число 0..9999, больше - "----"
{
if(n>9999)                              // в 4 разряда не влезает
{
  Ind[0]=0x40; Ind[1]=0x40; Ind[2]=0x40; Ind[3]=0x40;  // "----"
  return;                               // дальше не идём
}
Ind[0]=kod7[n/1000];                    // тысячи
Ind[1]=kod7[(n/100)%10];                // сотни
Ind[2]=kod7[(n/10)%10];                 // десятки
Ind[3]=kod7[n%10];                      // единицы
}

ISR(INT2_vect)                          // фронт из 0 в 1 на PB2: +1
{
if(cnt<10000){cnt++;}                   // дальше 10000 не считаем - всё равно "----"
}

ISR(TIMER1_COMPA_vect)                  // ровно раз в секунду: окно закрылось
{
show_num(cnt);                          // сколько фронтов пришло за секунду = частота, Гц
cnt=0;                                  // начинаем новую секунду
}

ISR(TIMER0_OVF_vect)                    // каждые 2,048 мс: динамическая индикация
{
PORTB=0xF4;                             // гасим все разряды, подтяжка PB2 остаётся
PORTD=Ind[i1];                          // сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после четвёртого - снова первый
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен (его входы - те же PB2, PB3)
DDRB=0xF8;                              // PB4..PB7 - разряды, PB3 - выход OC0; PB2 - вход
PORTB=0xF4;                             // разряды погашены, подтяжка на PB2: без сигнала там 1
DDRD=0xFF;                              // порт D - выходы (сегменты)
MCUCSR|= (1<<ISC2);                     // INT2 по фронту из 0 в 1
GIFR = (1<<INTF2);                      // смена ISC2 могла поставить флаг - сбрасываем (записью 1)
GICR|= (1<<INT2);                       // разрешаем прерывание INT2
OCR1A=31249;                            // Timer1 считает 0..31249: 31250 тиков по 32 мкс = 1 с
TCCR1A=0x00;                            // Timer1: выводы OC1A/OC1B не используем
TCCR1B|= (1<<CS12)|(1<<WGM12);          // Timer1: делитель 256, режим CTC - пошёл счёт
OCR0=127;                               // меандр на OC0: 128 тиков из 256 единица, 128 ноль
TCCR0|= (1<<WGM01)|(1<<WGM00);          // Timer0: режим Fast PWM, счёт 0..255 по кругу, как в Normal
TCCR0|= (1<<COM01);                     // выход OC0 (PB3): 1 с начала периода, 0 после совпадения с OCR0
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт: 8 МГц / 64 / 256 = 488 Гц
TIMSK|= (1<<OCIE1A)|(1<<TOIE0);         // разрешаем прерывания: совпадение A Timer1, переполнение Timer0
show_num(0);                            // на старте 0000
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывания
{
}
}
