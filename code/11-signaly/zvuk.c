// Глава 11, по желанию: пищалка модуля периферии. Пока нажата кнопка PC1, на PD7 меандр 1000 Гц.
// Звук делает Timer2 в режиме CTC: при каждом совпадении TCNT2 с OCR2 он сам переключает
// вывод OC2 (PD7). 8 МГц / 32 / (1+124) = 2000 переключений в секунду, то есть 1000 периодов.
// Timer0 только раз в 2,048 мс смотрит на кнопку.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   вход пищалки модуля периферии  -> PD7  (меандр; каким уровнем она включается, неизвестно)
//   кнопка блока "Кнопки"           -> PC1  (нажата = 0, нужна подтяжка)
//   гнёзд занято: 2 из 16
// Общий провод "Контроллера ПУ" и модуля периферии соединить.
//
// Пищалка бывает пассивной (звучит только от меандра) и активной (пищит сама от постоянного
// уровня). Какая на вашем модуле, неизвестно. Если пищит без нажатия, в main() поставьте
// PORTD=0x80 (в тишине на PD7 будет 1 вместо 0).

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

ISR(TIMER0_OVF_vect)                    // каждые 2,048 мс: смотрим на кнопку
{
if(!(PINC & (1<<PC1)))                  // кнопка нажата (на PC1 0)
{
  TCCR2|= (1<<COM20);                   // подключаем OC2: таймер сам переключает PD7 - звук
}
else                                    // кнопка отпущена
{
  TCCR2&=~(1<<COM20);                   // отключаем OC2: на PD7 снова бит PORTD - тишина
}
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRC=0x00;                              // порт C - вход
PORTC=0x02;                             // подтяжка на PC1: отпущена = 1, нажата = 0
DDRD=0x80;                              // PD7 (OC2) - выход на пищалку
PORTD=0x00;                             // в тишине на PD7 0
OCR2=124;                               // Timer2 считает 0..124: 125 тиков по 4 мкс = 0,5 мс
TCCR2|= (1<<WGM21);                     // Timer2: режим CTC (сброс при TCNT2==OCR2)
TCCR2|= (1<<CS21)|(1<<CS20);            // Timer2: делитель 32 (у Timer2 код 011 - это 32, у Timer0 - 64)
TIMSK|= (1<<TOIE0);                     // разрешаем прерывание по переполнению Timer0
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывание и таймеры
{
}
}
