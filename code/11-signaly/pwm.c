// Глава 11: яркость светодиода через ШИМ. Timer0 в режиме Fast PWM сам выдаёт на OC0 (PB3)
// прямоугольный сигнал 488 Гц, а долю периода, когда светодиод горит, задаёт число OCR0.
// PC1 - ярче, PC0 - тусклее, шагами по 10 %. На индикаторе - яркость в процентах, после старта 50.
// Тот же Timer0 продолжает крутить индикацию: в Fast PWM он, как и в Normal, переполняется
// каждые 256 тиков (2,048 мс), и прерывание TIMER0_OVF приходит с той же частотой.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка                -> PD0..PD7  (1 = горит)
//   разряды 1..4                        -> PB4..PB7  (0 = разряд включён)
//   светодиод блока "Светодиоды"        -> PB3       (выход OC0; светодиод "Контроллера ПУ" горит от 0)
//   кнопка "ярче" блока "Кнопки"        -> PC1       (нажата = 0, нужна подтяжка)
//   кнопка "тусклее" блока "Кнопки"     -> PC0       (нажата = 0, нужна подтяжка)
//   гнёзд занято: 15 из 16
//
// Светодиод горит от 0, поэтому ШИМ инверсный (COM01=1, COM00=1): на выходе 0 от начала периода
// до совпадения с OCR0, светодиод горит (OCR0+1)/256 периода. При OCR0=255 выход всё время 0 (100 %).
// А 0 % так не получить: даже при OCR0=0 остаётся вспышка в 1/256 периода, светодиод чуть светится.
// Поэтому на 0 % выход OC0 отключаем от вывода, и на PB3 остаётся бит PORTB = 1 (маски с "| 0x08").
// Если ваш светодиод горит от 1 (проверьте), ШИМ нужен прямой: в set_level() в строке, которая
// подключает OC0, уберите (1<<COM00), а в масках Mas и в обеих строках PORTB=0xF8 бит PB3
// сделайте 0: 0xE0, 0xD0, 0xB0, 0x70 и 0xF0.

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

unsigned char i1=0;                     // номер разряда, который горит сейчас (0..3)
char Mas[4]={0xE8,0xD8,0xB8,0x78};      // маски разрядов {PB4..PB7} + PB3 = 1 (бит 0x08): на 0 % не горит
char Ind[4];                            // что горит в каждом разряде (коды сегментов)
char kod7[10]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};  // коды цифр 0..9
const unsigned char pwm[11]={0,25,50,76,101,127,153,178,204,229,255};  // OCR0 для 0, 10, 20 .. 100 %
unsigned char level=5;                  // яркость 0..10 (в десятках процентов), на старте 50 %
unsigned char prev1=0x02;               // прошлое состояние PC1: 0x02 - отпущена
unsigned char prev0=0x01;               // прошлое состояние PC0: 0x01 - отпущена
unsigned char w1=0, w0=0;               // паузы антидребезга для каждой кнопки

void set_level(void)                    // применить яркость и показать её
{
if(level==0)                            // 0 %:
{
  TCCR0&=~((1<<COM01)|(1<<COM00));      // отключаем OC0 от вывода: на PB3 бит PORTB = 1, не горит
}
else                                    // 10..100 %:
{
  OCR0=pwm[level];                      // горит (OCR0+1)/256 периода
  TCCR0|= (1<<COM01)|(1<<COM00);        // подключаем OC0: инверсный ШИМ на PB3
}
Ind[0]=0x00;                            // разряд тысяч пустой
Ind[1]=(level==10) ? kod7[1] : 0x00;    // "1" только для 100 %
Ind[2]=(level==0)  ? 0x00 : kod7[level%10];  // десятки процентов (для 0 % - пусто)
Ind[3]=kod7[0];                         // единицы процентов всегда 0
}

ISR(TIMER0_OVF_vect)                    // ~488 раз в секунду: индикация и кнопки
{
unsigned char k;                        // текущее состояние кнопки
PORTB=0xF8;                             // гасим все разряды, PB3 = 1 (пока OC0 подключён, этот бит не действует)
PORTD=Ind[i1];                          // сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после четвёртого - снова первый

if(w1){w1--;}                           // кнопка PC1: идёт пауза - ждём
else
{
  k = PINC & 0x02;                      // читаем PC1: 0x02 - отпущена, 0 - нажата
  if(k != prev1)                        // состояние изменилось?
  {
    w1=10;                              // 20 мс не смотрим на кнопку (дребезг)
    if(k==0 && level<10){level++; set_level();}  // нажатие PC1: ярче
    prev1 = k;                          // запоминаем новое состояние
  }
}
if(w0){w0--;}                           // кнопка PC0: идёт пауза - ждём
else
{
  k = PINC & 0x01;                      // читаем PC0: 0x01 - отпущена, 0 - нажата
  if(k != prev0)                        // состояние изменилось?
  {
    w0=10;                              // 20 мс не смотрим на кнопку (дребезг)
    if(k==0 && level>0){level--; set_level();}  // нажатие PC0: тусклее
    prev0 = k;                          // запоминаем новое состояние
  }
}
}

int main(void)                          // отсюда программа начинается после включения
{
DDRC=0x00;                              // порт C - вход
PORTC=0x03;                             // подтяжка на PC0 и PC1: отпущена = 1, нажата = 0
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF8;                              // PB4..PB7 - разряды, PB3 - выход ШИМ (OC0)
PORTB=0xF8;                             // разряды погашены, PB3 = 1 - светодиод не горит
DDRD=0xFF;                              // порт D - выходы (сегменты)
TCCR0|= (1<<WGM01)|(1<<WGM00);          // Timer0: режим Fast PWM (счёт 0..255 по кругу)
set_level();                            // OCR0, выход OC0 и индикатор: 50 %
TIMSK|= (1<<TOIE0);                     // разрешаем прерывание по переполнению Timer0
TCCR0|= (1<<CS01)|(1<<CS00);            // делитель 64 - пошёл счёт: 8 МГц / 64 / 256 = 488 Гц
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывание и таймер
{
}
}
