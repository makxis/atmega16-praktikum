// Глава 9, доработка: секундомер MM:SS. PC1 - старт/стоп, PC0 - сброс.
// Старт и стоп делает сам Timer1: биты делителя CS = 0 - таймер стоит, CS12 = 1 - считает.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка -> PD0..PD7   (1 = горит)
//   разряды 1..4         -> PB4..PB7   (0 = разряд включён)
//   кнопка старт/стоп    -> PC1        (нажата = 0, нужна подтяжка)
//   кнопка сброс         -> PC0        (нажата = 0, нужна подтяжка)
//   гнёзд занято: 14 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов (PORTB, DDRD, TCCR0...)
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

unsigned char i1=0;                     // номер разряда, который горит сейчас (0..3)
char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски разрядов {PB4,PB5,PB6,PB7}: 0 в бите включает разряд
char Ind[4];                            // что горит в каждом разряде (коды сегментов)
char kod7[10]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};  // коды цифр 0..9
// kod7[n] - какие сегменты зажечь для цифры n: бит 0 = сегмент a (PD0) ... бит 6 = g (PD6)
unsigned char t1=0, t2=0, t3=0, t4=0;   // цифры часов: t1 - единицы секунд, t2 - десятки секунд,
                                        //              t3 - единицы минут, t4 - десятки минут
unsigned char prev1=0x02;               // прошлое состояние PC1: 0x02 - отпущена
unsigned char prev0=0x01;               // прошлое состояние PC0: 0x01 - отпущена
unsigned char w1=0, w0=0;               // паузы антидребезга для каждой кнопки

void show(void)                         // вывести цифры t4 t3 t2 t1 слева направо
{
Ind[0]=kod7[t4];                        // левый разряд: десятки минут
Ind[1]=kod7[t3];                        // единицы минут
Ind[2]=kod7[t2];                        // десятки секунд
Ind[3]=kod7[t1];                        // правый разряд: единицы секунд
}

void sw_toggle(void)                    // старт/стоп
{
if(TCCR1B & (1<<CS12))                  // таймер сейчас считает?
TCCR1B &= ~(1<<CS12);                   // да - останавливаем (делитель 0)
else
TCCR1B |= (1<<CS12);                    // нет - запускаем (делитель 256)
}

void sw_reset(void)                     // стоп и сброс в 00:00
{
TCCR1B &= ~(1<<CS12);                   // останавливаем таймер
TCNT1 = 0;                              // начатая секунда тоже обнуляется
t1=0; t2=0; t3=0; t4=0;                 // все цифры в 0
show();                                 // показать 00:00
}

ISR(TIMER0_OVF_vect)                    // прерывание Timer0: ~488 раз в секунду, за раз - один разряд
{
unsigned char k;                        // текущее состояние кнопки
PORTB=0xF0;                             // гасим все разряды (единицы на PB4..PB7)
PORTD=Ind[i1];                          // выставляем сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд (ноль в его бите)
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после четвёртого - снова первый

if(w1){w1--;}                           // кнопка PC1: идёт пауза - ждём
else
{
  k = PINC & 0x02;                      // читаем PC1: 0x02 - отпущена, 0 - нажата
  if(k != prev1)                        // состояние изменилось?
  {
    w1=10;                              // 20 мс не смотрим на кнопку (дребезг)
    if(k==0){sw_toggle();}              // нажатие PC1: старт/стоп
    prev1 = k;                          // запоминаем новое состояние
  }
}

if(w0){w0--;}                           // кнопка PC0: идёт пауза - ждём
else
{
  k = PINC & 0x01;                      // читаем PC0: 0x01 - отпущена, 0 - нажата
  if(k != prev0)                        // состояние изменилось?
  {
    w0=10;                              // 20 мс не смотрим на кнопку (дребезг)
    if(k==0){sw_reset();}               // нажатие PC0: сброс
    prev0 = k;                          // запоминаем новое состояние
  }
}
}

ISR(TIMER1_COMPA_vect)                  // прерывание Timer1: раз в секунду, пока таймер запущен
{
t1++;                                   // +1 секунда
if(t1==10){t1=0; t2++;                  // 10 с -> +1 к десяткам секунд
  if(t2==6){t2=0; t3++;                 // 60 с -> +1 минута
    if(t3==10){t3=0; t4++;              // 10 мин -> +1 к десяткам минут
      if(t4==6){t4=0;}}}}               // 60 мин -> 00:00 (}}} закрывают три if выше)
show();                                 // показать новое время
}

int main(void)                          // отсюда программа начинается после включения
{
DDRC=0x00;                              // порт C - вход
PORTC=0x03;                             // подтяжка на PC0 и PC1: отпущена = 1, нажата = 0
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (разряды)
DDRD=0xFF;                              // порт D - выходы (сегменты)
TIMSK|= (1<<OCIE1A)|(1<<TOIE0);         // разрешаем прерывания: совпадение A Timer1, переполнение Timer0
OCR1A=31249;                            // Timer1 считает 0..31249: 31250 тиков по 32 мкс = 1 с
TCCR1A=0x00;                            // Timer1: выводы OC1A/OC1B не используем
TCCR1B|= (1<<WGM12);                    // Timer1: режим CTC, делитель пока 0 - секундомер стоит
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт
show();                                 // на старте 00:00
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывания
{
}
}
