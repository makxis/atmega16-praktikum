// Глава 9, шаг 3: считаем момент нажатия (переход "отпущена - нажата").
// 20 нажатий = ровно 0020, удержание кнопки даёт +1, после 9999 идёт 0000.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка -> PD0..PD7   (1 = горит)
//   разряды 1..4         -> PB4..PB7   (0 = разряд включён)
//   кнопка               -> PC1        (нажата = 0, нужна подтяжка)
//   гнёзд занято: 13 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов (PORTB, DDRD, TCCR0...)
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

unsigned char i1=0;                     // номер разряда, который горит сейчас (0..3)
char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски разрядов {PB4,PB5,PB6,PB7}: 0 в бите включает разряд
char Ind[4];                            // что горит в каждом разряде (коды сегментов)
char kod7[10]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};  // коды цифр 0..9
// kod7[n] - какие сегменты зажечь для цифры n: бит 0 = сегмент a (PD0) ... бит 6 = g (PD6)
unsigned char t1=0, t2=0, t3=0, t4=0;   // цифры счётчика: t1 - единицы, t2 - десятки,
                                        //                t3 - сотни, t4 - тысячи
short i2=0;                             // пауза после изменения кнопки, в тиках Timer0
unsigned char prev=0x02;                // прошлое состояние кнопки: 0x02 - отпущена, 0 - нажата

void show(void)                         // вывести цифры t4 t3 t2 t1 слева направо
{
Ind[0]=kod7[t4];                        // левый разряд: тысячи
Ind[1]=kod7[t3];                        // сотни
Ind[2]=kod7[t2];                        // десятки
Ind[3]=kod7[t1];                        // правый разряд: единицы
}

void inc(void)                          // +1 к числу на индикаторе, до 9999
{
t1++;                                   // единицы
if(t1==10){t1=0; t2++;                  // 10 единиц -> +1 десяток
  if(t2==10){t2=0; t3++;                // 10 десятков -> +1 сотня
    if(t3==10){t3=0; t4++;              // 10 сотен -> +1 тысяча
      if(t4==10){t4=0;}}}}              // после 9999 - снова 0000 (}}} закрывают три if выше)
show();                                 // показать новое число
}

ISR(TIMER0_OVF_vect)                    // прерывание Timer0: ~488 раз в секунду, за раз - один разряд
{
unsigned char k;                        // текущее состояние кнопки
PORTB=0xF0;                             // гасим все разряды (единицы на PB4..PB7)
PORTD=Ind[i1];                          // выставляем сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд (ноль в его бите)
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после четвёртого - снова первый

if(i2!=0){i2--;}                        // идёт пауза - ждём, пока закончится дребезг
else
{
  k = PINC & 0x02;                      // читаем кнопку: 0x02 - отпущена, 0 - нажата
  if(k != prev)                         // состояние изменилось?
  {
    i2=10;                              // 20 мс не смотрим на кнопку (дребезг)
    if(k==0){inc();}                    // было отпущено, стало нажато - это нажатие: +1
    prev = k;                           // запоминаем новое состояние
  }
}
}

ISR(TIMER1_COMPA_vect)                  // Timer1 здесь не нужен, но его прерывание разрешено:
{                                       // обработчик обязан быть, хотя бы пустой, иначе программа
}                                       // будет перезапускаться раз в секунду

int main(void)                          // отсюда программа начинается после включения
{
DDRC=0x00;                              // порт C - вход
PORTC=0x02;                             // подтяжка на PC1: отпущена = 1, нажата = 0
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (разряды)
DDRD=0xFF;                              // порт D - выходы (сегменты)
TIMSK|= (1<<OCIE1A)|(1<<TOIE0);         // разрешаем прерывания: совпадение A Timer1, переполнение Timer0
OCR1A=31249;                            // Timer1 считает 0..31249: 31250 тиков по 32 мкс = 1 с
TCCR1A=0x00;                            // Timer1: выводы OC1A/OC1B не используем
TCCR1B|= (1<<CS12)|(1<<WGM12);          // Timer1: делитель 256, режим CTC - пошёл счёт
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт
show();                                 // на старте 0000
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывания
{
}
}
