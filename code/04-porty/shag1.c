// Глава 4, шаг 1: светодиод повторяет кнопку.
// Пока кнопка нажата, горит первый светодиод, отпустили - погас.
// Таймеров и прерываний нет: main() опрашивает кнопку в бесконечном цикле.
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиоды 1..4 -> PB4..PB7   (0 = горит; в этом шаге работает первый)
//   кнопка          -> PC1        (нажата = 0, нужна подтяжка)
//   гнёзд занято: 5 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <util/delay.h>                 // _delay_ms() - пауза

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (светодиоды)
PORTB=0xF0;                             // на выходах 1: все светодиоды погашены
DDRC=0x00;                              // порт C - вход
PORTC=0x02;                             // подтяжка на PC1: отпущена = 1, нажата = 0
while(1)                                // бесконечный цикл: опрос кнопки
{
  if(PINC & 0x02)                       // PC1 = 1: кнопка отпущена
  {
    PORTB|= 0x10;                       // 1 на PB4: первый светодиод погашен
  }
  else                                  // PC1 = 0: кнопка нажата
  {
    PORTB&= ~0x10;                      // 0 на PB4: первый светодиод горит
  }
  _delay_ms(10);                        // следующий опрос через 10 мс (100 раз в секунду)
}
}
