// Глава 4, задание 5: бегущий огонь, кнопка направления на PB2.
// Как в ogon.c: пока кнопка отпущена, огонь бежит вперёд, пока нажата - назад.
// Светодиоды и кнопка на одном порту B. Запись целого байта в PORTB задевает
// и бит 2, а это подтяжка кнопки. Поэтому в каждой записи в бите 2 стоит 1 (| 0x04).
// Без этого первая же запись PORTB=Mas[n] выключит подтяжку, и кнопка "нажмётся сама".
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиоды 1..4 -> PB4..PB7   (0 = горит)
//   кнопка          -> PB2        (нажата = 0, нужна подтяжка)
//   гнёзд занято: 5 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <util/delay.h>                 // _delay_ms() - пауза

char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски {PB4,PB5,PB6,PB7}: 0 в бите зажигает светодиод

int main(void)                          // отсюда программа начинается после включения
{
unsigned char n=0;                      // номер горящего светодиода 0..3
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (светодиоды), PB0..PB3 - входы
PORTB=0xF4;                             // светодиоды погашены (1), на PB2 подтяжка (1)
while(1)                                // бесконечный цикл: шаг огня
{
  PORTB=Mas[n] | 0x04;                  // горит светодиод n; 1 в бите 2 сохраняет подтяжку PB2
  _delay_ms(200);                       // ждём 0,2 с
  if(PINB & 0x04)                       // PB2 = 1: кнопка отпущена - вперёд
  {
    n++;                                // следующий светодиод
    if(n==4){n=0;}                      // после четвёртого - снова первый
  }
  else                                  // PB2 = 0: кнопка нажата - назад
  {
    if(n==0){n=3;} else {n--;}          // перед первым - четвёртый
  }
}
}
