// Глава 4, задание 1: бегущий огонь с двумя скоростями.
// Кнопка 1 (PC1), как в ogon.c, пока нажата, разворачивает огонь назад.
// Пока нажата кнопка 2 (PC0), огонь бежит в 4 раза быстрее: шаг 0,05 с вместо 0,2 с.
// _delay_ms() принимает только число, известное при компиляции, поэтому переменную паузу
// набираем из порций _delay_ms(10).
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиоды 1..4 -> PB4..PB7   (0 = горит)
//   кнопка 1        -> PC1        (нажата = 0, нужна подтяжка): направление
//   кнопка 2        -> PC0        (нажата = 0, нужна подтяжка): скорость
//   гнёзд занято: 6 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <util/delay.h>                 // _delay_ms() - пауза

char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски {PB4,PB5,PB6,PB7}: 0 в бите зажигает светодиод

int main(void)                          // отсюда программа начинается после включения
{
unsigned char n=0;                      // номер горящего светодиода 0..3
unsigned char t;                        // длина шага огня в порциях по 10 мс
unsigned char k;                        // счётчик порций паузы
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (светодиоды)
PORTB=0xF0;                             // на выходах 1: все светодиоды погашены
DDRC=0x00;                              // порт C - вход
PORTC=0x03;                             // подтяжка на PC0 и PC1: отпущена = 1, нажата = 0
while(1)                                // бесконечный цикл: шаг огня
{
  PORTB=Mas[n];                         // 0 только в бите PB(4+n): горит один светодиод
  if(PINC & 0x01){t=20;}                // PC0 = 1: кнопка 2 отпущена - шаг 20 x 10 мс = 0,2 с
  else {t=5;}                           // PC0 = 0: нажата - шаг 5 x 10 мс = 0,05 с
  for(k=0; k<t; k++)                    // пауза из t порций
  {
    _delay_ms(10);                      // одна порция: 10 мс
  }
  if(PINC & 0x02)                       // PC1 = 1: кнопка 1 отпущена - вперёд
  {
    n++;                                // следующий светодиод
    if(n==4){n=0;}                      // после четвёртого - снова первый
  }
  else                                  // PC1 = 0: кнопка 1 нажата - назад
  {
    if(n==0){n=3;} else {n--;}          // перед первым - четвёртый
  }
}
}
