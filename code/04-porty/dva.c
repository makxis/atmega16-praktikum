// Глава 4, задание 2: огонь шириной в два светодиода.
// Горят два соседних светодиода, пара сдвигается каждые 0,2 с: 1+2, 2+3, 3+4, 4+1, 1+2...
// Светодиод горит от 0, поэтому два огня - это И (&) двух масок: нули обеих масок остаются.
//
// ПОДКЛЮЧЕНИЕ (блок "Светодиоды" -> порты "Контроллера ПУ"):
//   светодиоды 1..4 -> PB4..PB7   (0 = горит)
//   гнёзд занято: 4 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <util/delay.h>                 // _delay_ms() - пауза

char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски {PB4,PB5,PB6,PB7}: 0 в бите зажигает светодиод

int main(void)                          // отсюда программа начинается после включения
{
unsigned char n=0;                      // первый светодиод пары 0..3
unsigned char m;                        // второй светодиод пары (сосед n)
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (светодиоды)
PORTB=0xF0;                             // на выходах 1: все светодиоды погашены
while(1)                                // бесконечный цикл: шаг огня
{
  m=n+1;                                // сосед следующий по порядку...
  if(m==4){m=0;}                        // ...а у четвёртого сосед - первый
  PORTB=Mas[n] & Mas[m];                // нули сразу в двух битах: горят два светодиода
  _delay_ms(200);                       // ждём 0,2 с
  n++;                                  // пара сдвигается на один
  if(n==4){n=0;}                        // после четвёртого - снова первый
}
}
