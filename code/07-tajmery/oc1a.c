// Глава 7: Timer1 сам мигает светодиодом на выводе OC1A (PD5) раз в секунду, без прерываний.
// Режим CTC: TCNT1 считает 0..OCR1A и сбрасывается в 0. При каждом совпадении TCNT1 с OCR1A
// таймер переключает вывод OC1A (COM1A1:COM1A0 = 01). Совпадение каждые 0,5 с:
// 8000000 / 256 = 31250 тиков в секунду, на 0,5 с - 15625 тиков, OCR1A = 15625 - 1 = 15624.
// Два переключения = период 1 с: полсекунды светодиод горит, полсекунды нет.
// Обработчиков нет, основной цикл пустой: после настройки процессор свободен.
//
// ПОДКЛЮЧЕНИЕ (блок "Светодиоды" -> порты "Контроллера ПУ"):
//   светодиод -> PD5          (0 = горит; PD5 - вывод OC1A таймера 1)
//   гнёзд занято: 1 из 16 (индикатор не подключайте: у него на PD5 сегмент f)

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRD|= (1<<PD5);                        // PD5 (OC1A) - выход: без этого сигнал таймера на гнездо не попадёт
OCR1A=15624;                            // совпадение каждые 15625 тиков по 32 мкс = 0,5 с
TCCR1A|= (1<<COM1A0);                   // при совпадении переключать OC1A (COM1A1:COM1A0 = 01)
TCCR1B|= (1<<WGM12)|(1<<CS12);          // режим CTC (вершина OCR1A), делитель 256 - пошёл счёт
while(1)                                // основной цикл пустой: всю работу делает таймер
{
}
}
