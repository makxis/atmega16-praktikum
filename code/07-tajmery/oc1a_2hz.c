// Глава 7, задание 1 (ответ): тот же светодиод на OC1A (PD5), но мигает 2 раза в секунду.
// Нужно переключение каждые 0,25 с. С делителем 256 это 7812,5 тика: нацело не делится,
// ровно 2 Гц не получится. С делителем 64: 8000000 / 64 = 125000 тиков в секунду,
// на 0,25 с - 31250 тиков, OCR1A = 31249 (влезает в 16 бит). Получается ровно 2 Гц.
//
// ПОДКЛЮЧЕНИЕ (блок "Светодиоды" -> порты "Контроллера ПУ"):
//   светодиод -> PD5          (0 = горит; PD5 - вывод OC1A таймера 1)
//   гнёзд занято: 1 из 16 (индикатор не подключайте: у него на PD5 сегмент f)

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRD|= (1<<PD5);                        // PD5 (OC1A) - выход
OCR1A=31249;                            // совпадение каждые 31250 тиков по 8 мкс = 0,25 с
TCCR1A|= (1<<COM1A0);                   // при совпадении переключать OC1A (COM1A1:COM1A0 = 01)
TCCR1B|= (1<<WGM12)|(1<<CS11)|(1<<CS10); // режим CTC (вершина OCR1A), делитель 64 - пошёл счёт
while(1)                                // основной цикл пустой: всю работу делает таймер
{
}
}
