// Глава 7, задание 2 (ответ): самое медленное мигание, которое Timer0 выдаёт на OC0 (PB3) сам.
// Больше всего у 8-битного таймера: делитель 1024 и OCR0 = 255, совпадение каждые
// 256 x 128 мкс = 32,768 мс. Переключение OC0 при каждом совпадении даёт меандр
// 8000000 / (2 x 1024 x 256) = 15,26 Гц: светодиод не мигает, а заметно мерцает.
// Медленнее аппаратно нельзя. 1 Гц на Timer0 получают только программно: счётчиком в прерывании.
//
// ПОДКЛЮЧЕНИЕ (блок "Светодиоды" -> порты "Контроллера ПУ"):
//   светодиод -> PB3          (0 = горит; PB3 - вывод OC0 таймера 0)
//   гнёзд занято: 1 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен (его вход AIN1 - тот же вывод PB3)
DDRB|= (1<<PB3);                        // PB3 (OC0) - выход
OCR0=255;                               // вершина счёта 255: больше у 8-битного таймера не бывает
TCCR0|= (1<<WGM01)|(1<<COM00)|(1<<CS02)|(1<<CS00); // CTC, переключать OC0, делитель 1024 - пошёл счёт
while(1)                                // основной цикл пустой: всю работу делает таймер
{
}
}
