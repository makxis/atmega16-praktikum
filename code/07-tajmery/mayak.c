// Режим 14 (Fast PWM, вершина ICR1): TCNT1 считает 0..ICR1 и сбрасывается.
// Делитель 256: 31250 тиков в секунду, ICR1 = 31250 - 1 = 31249, период ровно 1 с.
// Инверсный ШИМ (COM1A1:COM1A0 = 11): от начала периода до совпадения с OCR1A на выходе 0,
// светодиод горит (он горит от 0). OCR1A = 3125 - 1 = 3124: горит 3125 тиков = 0,1 с.
//
// ПОДКЛЮЧЕНИЕ (блок "Светодиоды" -> порты "Контроллера ПУ"):
//   светодиод -> PD5          (0 = горит; PD5 - вывод OC1A таймера 1)
