// Глава 5, шаг 1: стартовая программа (проект 444 в AVR Studio 4).
// Работает динамическая индикация, в kod7 найдены коды цифр 0..3,
// Timer1 настроен на 1 секунду, но его обработчик пока пустой.
// Рабочие строки исходные, добавлены только комментарии.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка   -> PD0..PD7   (1 = горит)
//   разряды Ind[0]..Ind[3] -> PB4..PB7   (0 = разряд включён)
//   гнёзд занято: 12 из 16 (и общий провод модулей соединить)

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR(), sei()
unsigned char i1=0;                     // номер текущего разряда 0..3
 char Mas[4]={0xE0,0xD0,0xB0,0x70}; //{PB4, PB5, PB6, PB7} - маски разрядов: 0 в нужном бите включает разряд
char Ind[4] = {0x3F, 0x06, 0x5B, 0x4F}; // что горит в каждом разряде (коды сегментов)
char kod7[10] = {0x3F, 0x06, 0x5B, 0x4F, 0x3F, 0x06, 0x5B, 0x4F, 0x5B, 0x4F}; // коды цифр: 0..3 найдены, 4..9 пока копии

ISR(TIMER0_OVF_vect)                    // ~488 раз в секунду: динамическая индикация
{

PORTB=0xF0;                             // гасим все разряды
PORTD=Ind[i1];                          // сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после 4-го снова первый
}

ISR(TIMER1_COMPA_vect)                  // раз в секунду (OCR1A=31249) - пока пусто, сюда пишем часы
{

}

int main(void)
{
ACSR|= (1<<ACD);                        // выключить аналоговый компаратор: он не нужен, а ток потребляет
DDRB=0xF0;                              // PB4..PB7 - выходы (разряды)
DDRD=0xFF;// 0b11111111                 // порт D - выходы (сегменты)
TIMSK|= (1<<OCIE1A)|(1<<TOIE0);         // разрешить прерывания: совпадение A Timer1 и переполнение Timer0
OCR1A=31249;                            // Timer1 считает 0..31249 = 31250 тиков по 32 мкс = 1 с
TCCR1A=0x00;                            // Timer1: выводы OC1A/OC1B не используются
TCCR1B|= (1<<CS12)|(1<<WGM12);          // Timer1: делитель 256, режим CTC (сброс при TCNT1==OCR1A)
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 (то же, что TCCR0=0x03)
Ind[0]=kod7[3]; Ind[1]=kod7[2]; Ind[2]=kod7[1]; Ind[3]=kod7[0]; // вывести цифры 3 2 1 0 в разряды Ind[0]..Ind[3]
sei();                                  // разрешить прерывания глобально

while(1)                                // основной цикл пустой - всё в прерываниях
{


}

}





