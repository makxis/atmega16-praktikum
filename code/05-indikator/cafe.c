// Глава 5, задание 3: слово CAFE на индикаторе.
// CAFE и BEEF - числа в шестнадцатеричной записи, поэтому kod7 дополнен кодами A b C d E F
// (номер кода = значение hex-цифры), а число раскладывается на 4 hex-цифры сдвигами.
// Чтобы увидеть bEEF, замените 0xCAFE на 0xBEEF.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g, точка   -> PD0..PD7   (1 = горит)
//   разряды Ind[0]..Ind[3] -> PB4..PB7   (0 = разряд включён)
//   гнёзд занято: 12 из 16 (и общий провод модулей соединить)

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов (PORTB, DDRD, TCCR0...)
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

unsigned char i1=0;                     // номер разряда, который горит сейчас (0..3)
char Mas[4]={0xE0,0xD0,0xB0,0x70};      // маски разрядов {PB4,PB5,PB6,PB7}: 0 в бите включает разряд
char Ind[4];                            // что горит в каждом разряде (коды сегментов)
char kod7[16]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F,  // коды цифр 0..9
               0x77,0x7C,0x39,0x5E,0x79,0x71};                       // коды букв A b C d E F
unsigned int slovo=0xCAFE;              // что показать: 4 hex-цифры = 4 разряда

ISR(TIMER0_OVF_vect)                    // прерывание Timer0: ~488 раз в секунду, за раз - один разряд
{
PORTB=0xF0;                             // гасим все разряды (единицы на PB4..PB7)
PORTD=Ind[i1];                          // выставляем сегменты текущего разряда
PORTB=Mas[i1];                          // включаем текущий разряд (ноль в его бите)
i1++;                                   // следующий разряд
if(i1==4){i1=0;}                        // после четвёртого - снова первый
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (разряды)
DDRD=0xFF;                              // порт D - выходы (сегменты)
TIMSK|= (1<<TOIE0);                     // разрешаем прерывание по переполнению Timer0 (Timer1 не нужен)
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт
Ind[0]=kod7[(slovo>>12) & 0x0F];        // старшая hex-цифра (C) - в левый разряд
Ind[1]=kod7[(slovo>>8) & 0x0F];         // вторая (A)
Ind[2]=kod7[(slovo>>4) & 0x0F];         // третья (F)
Ind[3]=kod7[slovo & 0x0F];              // младшая (E) - в правый разряд
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делают прерывания
{
}
}
