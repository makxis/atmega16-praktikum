// Глава 10, вариант А, задание 3: кодовый замок на одной цифре.
// Набираем 4 цифры: после каждой горит прочерк. После четвёртой: "O" - код верный, "E" - ошибка.
// "*" - начать заново. Подключение и опрос - как в kbd_hex.c, поменялась только key().
// Код 1234 (массив pass). Проверка: на старте индикатор пустой; 1, 2, 3, 4 - "O"; *, 1, 2, 3, 5 - "E".
//
// ПОДКЛЮЧЕНИЕ (модуль периферии -> "Контроллер ПУ"):
//   сегменты a..g        -> PD0..PD6            (1 = горит), точку не подключаем
//   разряд (любой один)  -> PB4                 (0 = включён, держим включённым всё время)
//   столбцы СТЛ1..СТЛ4   -> PB5, PB6, PB7, PD7  (выходы: опрашиваемый = 0, остальные = 1)
//   строки СТР1..СТР4    -> PB2, PB3, PC0, PC1  (входы с подтяжкой: нажата = 0)
//   гнёзд занято: 16 из 16
// Провода кнопок "Контроллера ПУ" с PC0 и PC1 снять: иначе кнопка сработает как клавиша "C" или "D".
//
// Клавиатура опрашивается в прерывании Timer0: за один вызов один столбец,
// полный проход по 4 столбцам - 8 мс. Клавиша засчитывается, когда 4 прохода подряд
// видно одно и то же (дребезг отфильтрован), и только один раз за нажатие.

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR() и sei() - для прерываний

#define NOKEY 0xFF                      // "ничего не нажато"

char kod16[16]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F,   // 0..9
                0x77,0x7C,0x39,0x5E,0x79,0x71};                       // A b C d E F
const unsigned char keys[4][4]={        // что на клавише [строка][столбец]:
  { 1, 2, 3,10},                        // 1 2 3 A
  { 4, 5, 6,11},                        // 4 5 6 B
  { 7, 8, 9,12},                        // 7 8 9 C
  {14, 0,15,13} };                      // * 0 # D   ("*" показываем как E, "#" как F)
unsigned char seg=0x00;                 // что горит на индикаторе: на старте пусто
const unsigned char pass[4]={1,2,3,4};  // правильный код
unsigned char pos=0;                    // сколько цифр уже набрано
unsigned char ok=1;                     // 1 - пока все цифры совпадают
unsigned char col=0;                    // опрашиваемый столбец 0..3
unsigned char found=NOKEY;              // клавиша, найденная за текущий проход
unsigned char last=NOKEY;               // что было на прошлом проходе
unsigned char same=0;                   // сколько проходов подряд видно одно и то же

unsigned char row(void)                 // номер строки, где 0 (нажата клавиша), или 4 - нигде
{
if(!(PINB & (1<<PB2))) return 0;        // СТР1
if(!(PINB & (1<<PB3))) return 1;        // СТР2
if(!(PINC & (1<<PC0))) return 2;        // СТР3
if(!(PINC & (1<<PC1))) return 3;        // СТР4
return 4;                               // нуля нет ни в одной строке
}

void key(unsigned char k)               // реакция на нажатие клавиши k (0..15)
{
if(k==14)                               // "*" - начать заново
{
  pos=0; ok=1; seg=0x00;                // ничего не набрано, индикатор пустой
}
else if(k<10 && pos<4)                  // цифра, и код ещё не набран целиком
{
  if(k!=pass[pos]){ok=0;}               // не совпала - запоминаем, но виду не подаём
  pos++;                                // набрана ещё одна цифра
  seg=0x40;                             // прочерк (сегмент g)
  if(pos==4)                            // набрали все 4
  {
    if(ok){seg=0x3F;}                   // "O" - открыто
    else  {seg=0x79;}                   // "E" - ошибка
  }
}                                       // буквы, "#" и цифры после четвёртой - не реагируем
}

ISR(TIMER0_OVF_vect)                    // прерывание Timer0: ~488 раз в секунду
{
unsigned char r;                        // номер строки
r=row();                                // столбец col стоит в 0 с прошлого вызова - читаем строки
if(r<4){found=keys[r][col];}            // нашли нажатую клавишу
col++;                                  // следующий столбец
if(col==4)                              // проход по всем столбцам закончен
{
  col=0;                                // новый проход - снова с первого столбца
  if(found==last)                       // то же, что в прошлый раз
  {
    if(same<10){same++;}                // сколько проходов подряд (дальше 10 не считаем)
    if(same==3 && last!=NOKEY){key(last);}  // 4 прохода подряд одно и то же - нажатие (ровно один раз)
  }
  else {last=found; same=0;}            // что-то поменялось (или дребезг) - считаем заново
  found=NOKEY;                          // новый проход начинаем с "ничего не нажато"
}
PORTB=0xEC;                             // PB5..PB7 = 1, PB4 = 0 (разряд горит), PB2, PB3 = 1 (подтяжка строк)
PORTD=seg|0x80;                         // сегменты; PD7 (столбец 4) = 1
if(col<3){PORTB&=~(0x20<<col);}         // 0 на столбец col: PB5, PB6 или PB7
else     {PORTD&=~0x80;}                // четвёртый столбец - PD7
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4 - разряд, PB5..PB7 - столбцы; PB2, PB3 - входы (строки)
PORTB=0xEC;                             // разряд включён, столбцы в 1, подтяжка на PB2, PB3
DDRC=0x00;                              // порт C - вход (PC0, PC1 - строки)
PORTC=0x03;                             // подтяжка на PC0, PC1
DDRD=0xFF;                              // PD0..PD6 - сегменты, PD7 - столбец 4
PORTD=seg|0x80;                         // индикатор пустой, PD7 = 1: до первого прерывания все столбцы в 1
TIMSK|= (1<<TOIE0);                     // разрешаем прерывание по переполнению Timer0
TCCR0|= (1<<CS01)|(1<<CS00);            // Timer0: делитель 64 - пошёл счёт
sei();                                  // разрешаем прерывания - с этого момента всё работает
while(1)                                // основной цикл пустой: всю работу делает прерывание
{
}
}
