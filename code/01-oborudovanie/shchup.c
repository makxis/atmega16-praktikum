// Глава 1: щуп уровней для проверки модуля периферии.
// PB4 всё время 0, PB5 всё время 1: к ним по очереди подключают проверяемый светодиод или пищалку.
// PB6 повторяет уровень на PC1 (вход с подтяжкой), PB7 повторяет уровень на PC0 (вход без подтяжки).
// Светодиоды "Контроллера ПУ" на PB6 и PB7 горят от 0, то есть горят, когда вход читает 0.
//
// ПОДКЛЮЧЕНИЕ (модуль периферии и блок "Светодиоды" -> "Контроллер ПУ"):
//   проверяемый светодиод или пищалка -> PB4, потом PB5 (PB4 всегда 0, PB5 всегда 1)
//   проверяемая кнопка                -> PC1, потом PC0 (PC1 с подтяжкой, PC0 без)
//   светодиод 1 "Контроллера ПУ"      -> PB6 (горит = PC1 читает 0)
//   светодиод 2 "Контроллера ПУ"      -> PB7 (горит = PC0 читает 0)
//   гнёзд занято: 6 из 16 (и общий провод модулей соединить)
// Проверка самого щупа: кнопка "Контроллера ПУ" на PC1 при нажатии зажигает светодиод на PB6,
// свободный светодиод "Контроллера ПУ" на PB4 горит, на PB5 не горит.

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц
#include <avr/io.h>                     // имена регистров и битов

int main(void)
{
unsigned char b;                        // что выдать в порт B
DDRB=0xF0;                              // PB4..PB7 - выходы
DDRC=0x00;                              // порт C - входы
PORTC=0x02;                             // подтяжка только на PC1, на PC0 её нет
while(1)                                // всё время повторяем входы на выходах
{
  b=0x20;                               // PB4 = 0, PB5 = 1, PB6 и PB7 пока 0
  if(PINC & 0x02) b|= 0x40;             // PC1 читает 1 -> PB6 = 1 (светодиод погашен)
  if(PINC & 0x01) b|= 0x80;             // PC0 читает 1 -> PB7 = 1 (светодиод погашен)
  PORTB=b;                              // выдать всё сразу
}
}
