// Глава 6, задание 2: сколько раз срабатывает INT0 за одно нажатие кнопки.
// Обработчик INT0 только прибавляет 1 к счётчику, а основной цикл каждые 20 мс
// показывает младшие 4 бита счётчика на четырёх светодиодах (двоичное число 0..15).
// Без дребезга одно нажатие давало бы +1. На стенде счёт часто прыгает сразу на 2..5:
// это отскоки контакта, каждый из них - ещё один спад на PD2.
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиоды 1..4 -> PB4..PB7   (0 = горит; на PB4 младший бит счёта)
//   кнопка          -> PD2        (вход INT0; нажата = 0, нужна подтяжка)
//   гнёзд занято: 5 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR(), sei()
#include <util/delay.h>                 // _delay_ms() - пауза

volatile unsigned char cnt=0;           // счётчик срабатываний: меняет прерывание, читает main

ISR(INT0_vect)                          // спад на PD2: нажатие или отскок контакта
{
cnt++;                                  // только считаем: обработчик должен быть коротким
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0xF0;                              // PB4..PB7 - выходы (светодиоды)
PORTB=0xF0;                             // на выходах 1: все светодиоды погашены
DDRD=0x00;                              // порт D - вход (PD2 = вход INT0)
PORTD=0x04;                             // подтяжка на PD2: отпущена = 1, нажата = 0
MCUCR|= (1<<ISC01);                     // INT0 по спаду: ISC01=1, ISC00=0
GIFR=(1<<INTF0);                        // сбросить флаг INT0, если он уже стоит (флаг сбрасывается записью 1)
GICR|= (1<<INT0);                       // разрешить прерывание INT0
sei();                                  // разрешить прерывания глобально (бит I в SREG)
while(1)                                // основной цикл: показываем счёт
{
  PORTB=0xF0 ^ (cnt<<4);                // биты 0..3 счёта на PB4..PB7; ^ 0xF0 инвертирует: светодиод горит от 0
  _delay_ms(20);                        // обновляем 50 раз в секунду
}
}
