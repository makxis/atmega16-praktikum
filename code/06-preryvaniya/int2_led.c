// Глава 6, задание 4: то же, что int0.c, но на INT2 (кнопка на PB2) и в момент отпускания.
// INT2 срабатывает только по перепаду, какому - выбирает бит ISC2 в MCUCSR: 0 - спад, 1 - фронт.
// Порядок смены ISC2: запретить INT2, сменить ISC2, сбросить флаг INTF2 записью 1, разрешить.
// Без сброса флага смена ISC2 может сама поставить INTF2, и прерывание сработает без нажатия.
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиод 1 -> PB4        (0 = горит; переключает прерывание)
//   светодиод 2 -> PB5        (0 = горит; мигает основной цикл)
//   кнопка      -> PB2        (вход INT2; нажата = 0, нужна подтяжка)
//   гнёзд занято: 3 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR(), sei()
#include <util/delay.h>                 // _delay_ms() - пауза

ISR(INT2_vect)                          // фронт на PB2 (с 0 на 1): кнопку отпустили
{
PORTB^= (1<<PB4);                       // переключаем светодиод 1 (бит подтяжки PB2 не трогаем)
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // компаратор не нужен (его вход AIN0 - тот же вывод PB2)
DDRB=0x30;                              // PB4, PB5 - выходы (светодиоды), PB2 - вход
PORTB=0x34;                             // светодиоды погашены (1), подтяжка на PB2: отпущена = 1, нажата = 0
GICR&= ~(1<<INT2);                      // 1) INT2 запрещён на время настройки
MCUCSR|= (1<<ISC2);                     // 2) INT2 по нарастающему фронту: момент отпускания
GIFR=(1<<INTF2);                        // 3) смена ISC2 могла поставить флаг - сбрасываем записью 1
GICR|= (1<<INT2);                       // 4) теперь разрешаем INT2
sei();                                  // разрешить прерывания глобально (бит I в SREG)
while(1)                                // основной цикл: мигаем светодиодом 2
{
  PORTB&= ~(1<<PB5);                    // светодиод 2 горит (одна команда cbi)
  _delay_ms(500);                       // полсекунды
  PORTB|= (1<<PB5);                     // светодиод 2 погашен (одна команда sbi)
  _delay_ms(500);                       // ещё полсекунды
}
}
