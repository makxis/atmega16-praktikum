// Глава 6, задание 3: флаг запоминает событие, даже когда прерывания запрещены.
// INT0 настроен и разрешён в GICR, но sei() вызывается только через 5 секунд после старта.
// Нажмите кнопку в эти 5 секунд (хоть несколько раз): светодиод 1 молчит, зато сразу
// после sei() переключается ровно один раз. Флаг INTF0 помнил, что нажатие было, но не сколько.
// Пока идут 5 секунд, светодиод 2 мигает часто, после sei() - раз в секунду.
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиод 1 -> PB4        (0 = горит; переключает прерывание)
//   светодиод 2 -> PB5        (0 = горит; мигает основной цикл)
//   кнопка      -> PD2        (вход INT0; нажата = 0, нужна подтяжка)
//   гнёзд занято: 3 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR(), sei()
#include <util/delay.h>                 // _delay_ms() - пауза

ISR(INT0_vect)                          // спад на PD2: кнопку нажали
{
PORTB^= (1<<PB4);                       // переключаем светодиод 1
}

int main(void)                          // отсюда программа начинается после включения
{
unsigned char i;                        // счётчик шагов ожидания
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0x30;                              // PB4, PB5 - выходы (светодиоды)
PORTB=0x30;                             // на выходах 1: оба светодиода погашены
DDRD=0x00;                              // порт D - вход (PD2 = вход INT0)
PORTD=0x04;                             // подтяжка на PD2: отпущена = 1, нажата = 0
MCUCR|= (1<<ISC01);                     // INT0 по спаду: ISC01=1, ISC00=0
GIFR=(1<<INTF0);                        // начинаем с чистым флагом
GICR|= (1<<INT0);                       // INT0 разрешён, но бит I в SREG пока 0: прерываний нет
for(i=0; i<25; i++)                     // 25 раз по 0,2 с = 5 секунд без sei()
{
  PORTB&= ~(1<<PB5);                    // светодиод 2 горит
  _delay_ms(100);                       // 0,1 с
  PORTB|= (1<<PB5);                     // светодиод 2 погашен
  _delay_ms(100);                       // 0,1 с
}
//GIFR=(1<<INTF0);                      // задание: уберите // в начале строки - нажатия до sei() забудутся
sei();                                  // бит I = 1: если флаг INTF0 стоит, обработчик вызовется сразу
while(1)                                // основной цикл: мигаем светодиодом 2 раз в секунду
{
  PORTB&= ~(1<<PB5);                    // светодиод 2 горит
  _delay_ms(500);                       // полсекунды
  PORTB|= (1<<PB5);                     // светодиод 2 погашен
  _delay_ms(500);                       // ещё полсекунды
}
}
