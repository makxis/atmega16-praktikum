// Глава 6: внешнее прерывание INT0. Кнопка на PD2 переключает светодиод 1,
// а основной цикл в это время мигает светодиодом 2 через _delay_ms().
// Светодиод 1 переключается сразу, даже посреди паузы: прерывание вклинивается в main.
// Кнопка без защиты от дребезга, поэтому иногда одно нажатие переключает светодиод
// несколько раз подряд (и кажется, что он не реагирует). Как с этим бороться: глава 9.
//
// ПОДКЛЮЧЕНИЕ (блоки "Светодиоды" и "Кнопки" -> порты "Контроллера ПУ"):
//   светодиод 1 -> PB4        (0 = горит; переключает прерывание)
//   светодиод 2 -> PB5        (0 = горит; мигает основной цикл)
//   кнопка      -> PD2        (вход INT0; нажата = 0, нужна подтяжка)
//   гнёзд занято: 3 из 16

#define F_CPU 8000000UL                 // тактовая частота МК: 8 МГц (нужна для _delay_ms)
#include <avr/io.h>                     // имена регистров и битов
#include <avr/interrupt.h>              // ISR(), sei()
#include <util/delay.h>                 // _delay_ms() - пауза

ISR(INT0_vect)                          // спад на PD2 (с 1 на 0): кнопку нажали или контакт отскочил
{
PORTB^= (1<<PB4);                       // переключаем светодиод 1
}

int main(void)                          // отсюда программа начинается после включения
{
ACSR|= (1<<ACD);                        // аналоговый компаратор не нужен - выключаем
DDRB=0x30;                              // PB4, PB5 - выходы (светодиоды)
PORTB=0x30;                             // на выходах 1: оба светодиода погашены
DDRD=0x00;                              // порт D - вход (PD2 = вход INT0)
PORTD=0x04;                             // подтяжка на PD2: отпущена = 1, нажата = 0
MCUCR|= (1<<ISC01);                     // INT0 по спаду: ISC01=1, ISC00=0
GIFR=(1<<INTF0);                        // сбросить флаг INT0, если он уже стоит (флаг сбрасывается записью 1)
GICR|= (1<<INT0);                       // разрешить прерывание INT0
sei();                                  // разрешить прерывания глобально (бит I в SREG)
while(1)                                // основной цикл: мигаем светодиодом 2
{
  PORTB&= ~(1<<PB5);                    // светодиод 2 горит (одна команда cbi: прерывание её не разорвёт)
  _delay_ms(500);                       // полсекунды
  PORTB|= (1<<PB5);                     // светодиод 2 погашен (одна команда sbi)
  _delay_ms(500);                       // ещё полсекунды
}
}
